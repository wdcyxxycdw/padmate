// Command codegen generates consumed Go decoding types and frontend schema
// types from the canonical JSON schemas. Go representation annotations keep
// omission semantics and raw unions compatible with the semantic parser.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

type node map[string]any

func main() {
	root := flag.String("root", "..", "repository root")
	check := flag.Bool("check", false, "compare generated files without writing")
	flag.Parse()
	files, err := generate(*root)
	if err == nil {
		err = writeFiles(files, *check)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "codegen:", err)
		os.Exit(1)
	}
}

func obj(v any) node {
	if m, ok := v.(map[string]any); ok {
		return m
	}
	return nil
}
func str(n node, key string) string { v, _ := n[key].(string); return v }
func names(n node) []string {
	keys := make([]string, 0, len(n))
	for key := range n {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
func upper(s string) string {
	if s == "" {
		return ""
	}
	if s == "$schema" {
		return "Schema"
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
func list(v any) []string {
	var out []string
	for _, x := range arr(v) {
		if s, ok := x.(string); ok {
			out = append(out, s)
		}
	}
	return out
}
func arr(v any) []any { a, _ := v.([]any); return a }

type generator struct {
	goTypes map[string]string
	ts      strings.Builder
}

func generate(root string) (map[string][]byte, error) {
	g := generator{goTypes: map[string]string{}}
	g.ts.WriteString("// Code generated by daemon/tools/codegen from schema/*.schema.json. DO NOT EDIT.\n\n")
	for _, kind := range []string{"profile", "config", "state"} {
		data, err := os.ReadFile(filepath.Join(root, "schema", kind+".schema.json"))
		if err != nil {
			return nil, err
		}
		var schema node
		if err := json.Unmarshal(data, &schema); err != nil {
			return nil, err
		}
		defs := obj(schema["$defs"])
		if err := g.emitGo(schema, defs); err != nil {
			return nil, err
		}
		for _, name := range names(defs) {
			if err := g.emitGo(obj(defs[name]), defs); err != nil {
				return nil, err
			}
		}
		for _, n := range obj(schema["properties"]) {
			if child := obj(n); str(child, "x-go-name") != "" {
				if err := g.emitGo(child, defs); err != nil {
					return nil, err
				}
			}
		}
		prefix := upper(kind)
		fmt.Fprintf(&g.ts, "export type %s = %s;\n\n", prefix, tsType(schema, prefix, defs))
		for _, name := range names(defs) {
			fmt.Fprintf(&g.ts, "export type %s%s = %s;\n\n", prefix, upper(name), tsType(obj(defs[name]), prefix, defs))
		}
	}
	var goSrc strings.Builder
	goSrc.WriteString("// Code generated by tools/codegen from schema/*.schema.json. DO NOT EDIT.\npackage profile\n\nimport \"encoding/json\"\n\n")
	for _, name := range namesString(g.goTypes) {
		goSrc.WriteString(g.goTypes[name])
		goSrc.WriteByte('\n')
	}
	formatted, err := format.Source([]byte(goSrc.String()))
	if err != nil {
		return nil, err
	}
	return map[string][]byte{filepath.Join(root, "daemon/internal/profile/wire_generated.go"): formatted, filepath.Join(root, "app/src/shared/generated/schema.ts"): []byte(strings.TrimRight(g.ts.String(), "\n") + "\n")}, nil
}

func namesString(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

func (g *generator) emitGo(n, defs node) error {
	name := str(n, "x-go-name")
	if name == "" || n["x-go-skip"] == true {
		return nil
	}
	var b strings.Builder
	switch {
	case n["x-go-map"] == true:
		t, err := goType(obj(n["additionalProperties"]), defs, false)
		if err != nil {
			return err
		}
		fmt.Fprintf(&b, "type %s map[string]%s\n", name, t)
	case n["x-go-layer"] == true:
		props := obj(n["properties"])
		for key, v := range props {
			if key != "color" && str(obj(v), "$ref") != "#/$defs/binding" {
				return fmt.Errorf("unsupported layer property %s", key)
			}
		}
		fmt.Fprintf(&b, "type %s struct { Color *string; Bindings map[string]*wireBinding }\n", name)
	default:
		props := node{}
		for key, v := range obj(n["properties"]) {
			props[key] = v
		}
		for _, merge := range list(n["x-go-merge"]) {
			for key, v := range obj(obj(defs[merge])["properties"]) {
				if props[key] == nil {
					props[key] = v
				}
			}
		}
		if len(props) == 0 {
			return fmt.Errorf("go struct %s has no properties", name)
		}
		fmt.Fprintf(&b, "type %s struct {\n", name)
		required := list(n["required"])
		for _, key := range names(props) {
			property := obj(props[key])
			// A property the daemon accepts but no longer reads, such as a
			// deprecated config.json member, has no Go field.
			if property["x-go-skip"] == true {
				continue
			}
			field := str(property, "x-go-field")
			if field == "" {
				field = upper(key)
			}
			typ, err := goType(property, defs, !slices.Contains(required, key))
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, key, err)
			}
			tag := key
			if name == "State" || name == "LayerMemory" {
				if !slices.Contains(required, key) {
					tag += ",omitempty"
				}
			}
			fmt.Fprintf(&b, "%s %s `json:%q`\n", field, typ, tag)
		}
		b.WriteString("}\n")
	}
	definition := b.String()
	if old := g.goTypes[name]; old != "" && old != definition {
		return fmt.Errorf("schemas disagree on shared Go type %s", name)
	}
	g.goTypes[name] = definition
	return nil
}

func goType(n, defs node, optional bool) (string, error) {
	if typ := str(n, "x-go-type"); typ != "" {
		if err := checkGoRepresentation(n, defs, typ); err != nil {
			return "", err
		}
		return typ, nil
	}
	if ref := str(n, "$ref"); ref != "" {
		name := str(obj(defs[strings.TrimPrefix(ref, "#/$defs/")]), "x-go-name")
		if name == "" {
			return "", fmt.Errorf("missing Go name for %s", ref)
		}
		if optional {
			return "*" + name, nil
		}
		return name, nil
	}
	typ := str(n, "type")
	if types := list(n["type"]); len(types) > 0 {
		optional = slices.Contains(types, "null")
		for _, t := range types {
			if t != "null" {
				typ = t
				break
			}
		}
	}
	if typ == "" {
		if e := arr(n["enum"]); len(e) > 0 {
			switch e[0].(type) {
			case string:
				typ = "string"
			default:
				typ = "number"
			}
		} else {
			switch n["const"].(type) {
			case string:
				typ = "string"
			case float64:
				typ = "integer"
			case bool:
				typ = "boolean"
			}
		}
	}
	var out string
	switch typ {
	case "string":
		out = "string"
	case "integer":
		out = "int"
	case "number":
		out = "float64"
	case "boolean":
		out = "bool"
	case "array":
		t, err := goType(obj(n["items"]), defs, false)
		return "[]" + t, err
	case "object":
		add := obj(n["additionalProperties"])
		if add != nil {
			t, err := goType(add, defs, false)
			return "map[string]" + t, err
		}
		if len(obj(n["properties"])) == 0 {
			return "map[string]any", nil
		}
		return "", errors.New("named object requires a Go representation annotation")
	default:
		return "", errors.New("union requires an explicit raw Go decoding representation")
	}
	if optional {
		out = "*" + out
	}
	return out, nil
}

// Representation annotations choose omission/default and raw-union decoding,
// not the schema's value kind. Reject a stale annotation when that kind changes.
func checkGoRepresentation(n, defs node, typ string) error {
	if typ == "json.RawMessage" {
		if len(arr(n["oneOf"])) == 0 && len(arr(n["anyOf"])) == 0 {
			return errors.New("raw JSON representation requires a schema union")
		}
		return nil
	}
	base := strings.TrimPrefix(typ, "*")
	if ref := str(n, "$ref"); ref != "" {
		want := str(obj(defs[strings.TrimPrefix(ref, "#/$defs/")]), "x-go-name")
		if base != want {
			return fmt.Errorf("go representation %s disagrees with schema reference %s", typ, ref)
		}
		return nil
	}
	kind := schemaKind(n)
	if types := list(n["type"]); slices.Contains(types, "null") && !strings.HasPrefix(typ, "*") && !strings.HasPrefix(typ, "map[") && !strings.HasPrefix(typ, "[]") {
		return fmt.Errorf("nullable schema requires a nullable Go representation, got %s", typ)
	}
	valid := false
	switch kind {
	case "string":
		valid = base == "string"
	case "boolean":
		valid = base == "bool"
	case "integer":
		valid = base == "int" || base == "json.Number" || base == "float64"
	case "number":
		valid = base == "float64" || base == "json.Number"
	case "array":
		if strings.HasPrefix(base, "[]") {
			return checkGoRepresentation(obj(n["items"]), defs, strings.TrimPrefix(base, "[]"))
		}
	case "object":
		if base == str(n, "x-go-name") && base != "" {
			return nil
		}
		if strings.HasPrefix(base, "map[string]") {
			item := strings.TrimPrefix(base, "map[string]")
			if additional := obj(n["additionalProperties"]); additional != nil {
				return checkGoRepresentation(additional, defs, item)
			}
			props := obj(n["properties"])
			if len(props) == 0 {
				valid = item == "any"
				break
			}
			for _, property := range props {
				if err := checkGoRepresentation(obj(property), defs, item); err != nil {
					return err
				}
			}
			return nil
		}
	}
	if !valid {
		return fmt.Errorf("go representation %s cannot represent schema %s", typ, kind)
	}
	return nil
}

func schemaKind(n node) string {
	if kind := str(n, "type"); kind != "" {
		return kind
	}
	for _, kind := range list(n["type"]) {
		if kind != "null" {
			return kind
		}
	}
	var sample any
	if values := arr(n["enum"]); len(values) > 0 {
		sample = values[0]
	} else {
		sample = n["const"]
	}
	switch sample.(type) {
	case string:
		return "string"
	case bool:
		return "boolean"
	case float64:
		return "integer"
	}
	return "union"
}

func literal(v any) string { data, _ := json.Marshal(v); return string(data) }
func tsType(n node, prefix string, defs node) string {
	if n["x-ts-never"] == true {
		return "never"
	}
	if ref := str(n, "$ref"); ref != "" {
		return prefix + upper(strings.TrimPrefix(ref, "#/$defs/"))
	}
	// The schema's discriminator selects one strict action shape.
	if str(n, "x-go-name") == "wireAction" {
		var variants []string
		for _, condition := range arr(n["allOf"]) {
			ref := str(obj(obj(condition)["then"]), "$ref")
			if ref != "" {
				variants = append(variants, prefix+upper(strings.TrimPrefix(ref, "#/$defs/")))
			}
		}
		if len(variants) > 0 {
			return strings.Join(variants, " | ")
		}
	}
	for _, keyword := range []string{"oneOf", "anyOf"} {
		if variants := arr(n[keyword]); len(variants) > 0 {
			types := make([]string, 0, len(variants))
			for _, v := range variants {
				types = append(types, tsType(obj(v), prefix, defs))
			}
			return strings.Join(types, " | ")
		}
	}
	if values := arr(n["enum"]); len(values) > 0 {
		var types []string
		for _, v := range values {
			types = append(types, literal(v))
		}
		return strings.Join(types, " | ")
	}
	if v, ok := n["const"]; ok {
		return literal(v)
	}
	if types := list(n["type"]); len(types) > 0 {
		var out []string
		for _, typ := range types {
			clone := node{}
			for k, v := range n {
				clone[k] = v
			}
			clone["type"] = typ
			out = append(out, tsType(clone, prefix, defs))
		}
		return strings.Join(out, " | ")
	}
	switch str(n, "type") {
	case "null":
		return "null"
	case "string":
		return "string"
	case "boolean":
		return "boolean"
	case "integer", "number":
		return "number"
	case "array":
		return "Array<" + tsType(obj(n["items"]), prefix, defs) + ">"
	case "object":
		if branches := conditionalObjectTypes(n, prefix, defs); len(branches) > 0 {
			return "(" + strings.Join(branches, " | ") + ")"
		}
		props := obj(n["properties"])
		additional := obj(n["additionalProperties"])
		if len(props) == 0 {
			if additional != nil {
				return "Record<string, " + tsType(additional, prefix, defs) + ">"
			}
			return "Record<string, unknown>"
		}
		required := list(n["required"])
		// Action discriminator is required by the surrounding action schema.
		if t := obj(props["type"]); t != nil && t["const"] != nil {
			required = append(required, "type")
		}
		var b strings.Builder
		b.WriteString("{\n")
		for _, key := range names(props) {
			optional := "?"
			if slices.Contains(required, key) {
				optional = ""
			}
			fmt.Fprintf(&b, "  %s%s: %s;\n", literal(key), optional, tsType(obj(props[key]), prefix, defs))
		}
		b.WriteString("}")
		if additional != nil {
			b.WriteString(" & Record<string, " + tsType(additional, prefix, defs) + ">")
		}
		return b.String()
	default:
		return "unknown"
	}
}

// The layer schema splits its operation enum into complete conditional
// branches. Preserve each branch's required and forbidden fields in TS.
func conditionalObjectTypes(n node, prefix string, defs node) []string {
	conditions := arr(n["allOf"])
	if len(conditions) == 0 {
		return nil
	}
	props := obj(n["properties"])
	var out []string
	covered := map[string][]string{}
	for _, v := range conditions {
		condition := obj(v)
		when := obj(obj(condition["if"])["properties"])
		then := obj(condition["then"])
		if len(when) != 1 || len(list(then["required"])) == 0 {
			return nil
		}
		copyNode := node{}
		for k, value := range n {
			if k != "allOf" {
				copyNode[k] = value
			}
		}
		copyProps := node{}
		for k, value := range props {
			copyProps[k] = value
		}
		for key, shape := range when {
			constraint := obj(shape)
			if len(arr(constraint["enum"])) == 0 && constraint["const"] == nil {
				return nil
			}
			copyProps[key] = map[string]any(constraint)
			values := list(constraint["enum"])
			if v, ok := constraint["const"].(string); ok {
				values = []string{v}
			}
			covered[key] = append(covered[key], values...)
		}
		for _, key := range list(obj(then["not"])["required"]) {
			copyProps[key] = map[string]any{"x-ts-never": true}
		}
		copyNode["properties"] = map[string]any(copyProps)
		required := list(n["required"])
		required = append(required, list(then["required"])...)
		req := make([]any, len(required))
		for i, key := range required {
			req[i] = key
		}
		copyNode["required"] = req
		out = append(out, tsType(copyNode, prefix, defs))
	}
	for key, coveredValues := range covered {
		values := list(obj(props[key])["enum"])
		if len(values) == 0 {
			return nil
		}
		for _, v := range values {
			if !slices.Contains(coveredValues, v) {
				return nil
			}
		}
	}
	return out
}

func writeFiles(files map[string][]byte, check bool) error {
	for _, path := range fileNames(files) {
		want := files[path]
		if check {
			got, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(got, want) {
				return fmt.Errorf("%s is stale; run task gen", path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			return err
		}
	}
	return nil
}
func fileNames(files map[string][]byte) []string {
	out := make([]string, 0, len(files))
	for path := range files {
		out = append(out, path)
	}
	slices.Sort(out)
	return out
}
