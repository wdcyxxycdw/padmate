package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"runtime/debug"
	"slices"
	"strings"
)

const (
	gojaModule    = "github.com/dop251/goja"
	esbuildModule = "github.com/evanw/esbuild"
)

// versions are the goja and esbuild module versions, as "path version".
type versions struct {
	goja, esbuild string
}

// buildVersions reads the module versions linked into this binary, so the
// header always names the goja that produced the results.
func buildVersions() (versions, error) {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return versions{}, errors.New("no build info in this binary")
	}
	find := func(path string) (string, error) {
		for _, d := range info.Deps {
			if d.Path != path {
				continue
			}
			if d.Replace != nil {
				d = d.Replace
			}
			return d.Path + " " + d.Version, nil
		}
		return "", fmt.Errorf("module %s not in build info", path)
	}
	var v versions
	var err error
	if v.goja, err = find(gojaModule); err != nil {
		return versions{}, err
	}
	if v.esbuild, err = find(esbuildModule); err != nil {
		return versions{}, err
	}
	return v, nil
}

// featuresFile is the layout of goja_features.json. Field order is fixed by
// the struct; encoding/json sorts the map keys.
type featuresFile struct {
	Comment   string            `json:"comment"`
	Goja      string            `json:"goja"`
	Esbuild   string            `json:"esbuild"`
	Supported map[string]bool   `json:"supported"`
	Notes     map[string]string `json:"notes"`
}

// renderFeatures formats goja_features.json.
func renderFeatures(v versions, results map[string]featureResult) ([]byte, error) {
	f := featuresFile{
		Comment:   "Code generated by daemon/tools/gojafeatures (go generate ./internal/script/compile); DO NOT EDIT. \"supported\" is esbuild's BuildOptions.Supported for goja; \"notes\" says why a feature is false.",
		Goja:      v.goja,
		Esbuild:   v.esbuild,
		Supported: make(map[string]bool, len(results)),
		Notes:     map[string]string{},
	}
	for name, r := range results {
		f.Supported[name] = r.supported
		if r.note != "" {
			f.Notes[name] = r.note
		}
	}
	data, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// renderLib formats lib.padmate-goja.d.ts.
func renderLib(v versions, results []libResult) []byte {
	var b bytes.Buffer
	line := func(format string, args ...any) {
		fmt.Fprintf(&b, format, args...)
		b.WriteByte('\n')
	}
	line("// Code generated by daemon/tools/gojafeatures (go generate ./internal/script/compile); DO NOT EDIT.")
	line("//")
	line("// The TypeScript standard library that goja provides, probed with")
	line("// %s.", v.goja)
	line("//")
	line("// Use it with \"lib\": [] in tsconfig.json. Do not use \"noLib\": true:")
	line("// tsc ignores /// <reference lib> directives under noLib.")
	line("//")
	line("// goja has no Intl, so the *.intl components are not referenced. tsc")
	line("// still knows part of Intl: es5 declares Intl.Collator, Intl.NumberFormat")
	line("// and Intl.DateTimeFormat, and es2020.bigint, es2020.date, es2020.number")
	line("// and es2020.string reference es2020.intl (which references es2018.intl).")
	line("// Such code type-checks but throws a ReferenceError in goja.")

	var partial, excluded, unreferenced []libResult
	for _, r := range results {
		switch {
		case r.component.unreferenced:
			unreferenced = append(unreferenced, r)
		case !r.included():
			excluded = append(excluded, r)
		case len(r.missing) > 0 || len(r.optional) > 0 || r.component.note != "":
			partial = append(partial, r)
		}
	}
	section := func(title string, rs []libResult, describe func(libResult) string) {
		if len(rs) == 0 {
			return
		}
		line("//")
		for _, l := range wrap(title, 76) {
			line("// %s", strings.TrimPrefix(l, "  "))
		}
		for _, r := range rs {
			for _, l := range wrap(r.component.name+": "+describe(r), 72) {
				line("//   %s", l)
			}
		}
	}
	section("Referenced, with notes:", partial, func(r libResult) string {
		var parts []string
		if lacks := slices.Concat(r.missing, r.optional); len(lacks) > 0 {
			parts = append(parts, "goja lacks "+strings.Join(lacks, ", "))
		}
		for _, n := range []string{r.component.lowered, r.component.note} {
			if n != "" {
				parts = append(parts, n)
			}
		}
		return strings.Join(parts, "; ")
	})
	section("Not referenced (goja lacks the members listed):", excluded, func(r libResult) string {
		s := strings.Join(r.missing, ", ")
		if r.component.note != "" {
			s += " (" + r.component.note + ")"
		}
		return s
	})
	section("Never referenced: TypeScript 5.9 (Monaco 0.56) has no es2025.* libs, and esnext.* content changes between TypeScript versions (esnext.collection is the Set methods in 5.9 and Map.getOrInsert in 6.0):", unreferenced, func(r libResult) string {
		s := "goja has it"
		if len(r.missing) > 0 {
			s = "goja lacks " + strings.Join(r.missing, ", ")
		}
		if r.component.note != "" {
			s += " (" + r.component.note + ")"
		}
		return s
	})
	line("")
	for _, r := range results {
		if r.included() {
			line("/// <reference lib=%q />", r.component.name)
		}
	}
	return b.Bytes()
}

// wrap splits s into lines of at most width bytes at spaces, indenting
// continuation lines by two spaces. A word longer than width stays whole.
func wrap(s string, width int) []string {
	var lines []string
	cur := ""
	for _, w := range strings.Fields(s) {
		switch {
		case cur == "":
			cur = w
		case len(cur)+1+len(w) > width:
			lines = append(lines, cur)
			cur = "  " + w
		default:
			cur += " " + w
		}
	}
	if cur != "" {
		lines = append(lines, cur)
	}
	return lines
}
