// Package cspnames finds the names CLIP STUDIO PAINT (CSP) shows for its
// commands (ADR-0019). The shortcut file holds only command ids such as
// "filenew"; the text lives elsewhere:
//
//   - Menu commands: the main resource under resource\<language>\ of the
//     install folder has the menus, with the label of every item and the menu
//     path. It is read at run time, so it follows the user's CSP version.
//   - Other commands (canvas scrolling, tool property plus and minus, next
//     sub tool and so on): CSP hard-codes the text in its executable. The
//     package ships a table extracted from CSP 5.1.5 (table.json,
//     regenerated by `padmate-probe csp-names`).
//   - Filter plug-ins, whose ids are GUIDs: the name is a string resource in
//     the plug-in DLL, read at run time.
//
// Command looks them up in that order; a command found in none has no name
// and the caller shows the id. The package has no platform dependencies.
// The container format is undocumented; the parser is defensive and reports
// anything unexpected as ErrUnknownFormat.
package cspnames

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"strings"
)

// Category is a group of commands: a top-level menu or a group of the
// shortcut dialog outside the menus.
type Category struct {
	// ID is stable ASCII, the same in every language and CSP language.
	ID string
	// Name is the localized name.
	Name string
}

type menuEntry struct {
	name     string
	path     []string
	category string
}

type tableEntry struct {
	name     string
	path     []string
	category string
}

// Names resolves command ids to names. It is safe for concurrent use.
type Names struct {
	zh    bool
	menu  map[string]menuEntry
	table map[string]tableEntry
	plug  *plugins
	cats  []Category
	// MenuCount is the number of commands the menu resource named.
	menuCount int
}

// Language returns the CSP resource folder for a padmate UI language:
// "zh-CN" gives "chinese_sc"; everything else gives "english".
func Language(lang string) string {
	if isChinese(lang) {
		return "chinese_sc"
	}
	return "english"
}

func isChinese(lang string) bool {
	l := strings.ToLower(strings.ReplaceAll(lang, "_", "-"))
	return l == "zh" || strings.HasPrefix(l, "zh-") || l == "chinese_sc"
}

// Load reads the names of the CSP installed in installDir, the folder that
// holds CLIPStudioPaint.exe and resource\. lang is padmate's UI language
// ("zh-CN" or "en").
//
// A resource that cannot be read or parsed is not fatal: Load then returns
// Names that use the bundled table and the plug-ins only, together with the
// error (for logging; it wraps ErrUnknownFormat when the structure was not
// understood). The returned *Names is never nil.
func Load(installDir, lang string) (*Names, error) {
	return loadFS(os.DirFS(installDir), lang)
}

func loadFS(fsys fs.FS, lang string) (*Names, error) {
	zh := isChinese(lang)
	n := &Names{
		zh:    zh,
		menu:  map[string]menuEntry{},
		table: map[string]tableEntry{},
		plug:  newPlugins(fsys, zh),
	}
	t, err := BundledTable()
	if err != nil {
		return n, err
	}
	tableCats := map[string]string{} // localized name to id
	tableCatName := map[string]string{}
	for _, c := range t.Categories {
		name := c.EN
		if zh {
			name = c.ZH
		}
		tableCatName[c.ID] = name
		if _, ok := tableCats[name]; !ok {
			tableCats[name] = c.ID
		}
	}
	for id, c := range t.Commands {
		name, p := c.pick(zh)
		cat := c.Category
		n.table[id] = tableEntry{name: name, path: p, category: cat}
	}

	res, menuErr := readMenuResource(fsys, Language(lang))
	usedCats := map[string]bool{}
	if res != nil {
		catOf := map[uint32]string{} // top-level menu to category id
		for _, top := range res.Tops {
			if top.Name == "" {
				continue
			}
			id, ok := tableCats[top.Name]
			if !ok {
				id = fmt.Sprintf("menu%d", top.ID)
			}
			catOf[top.ID] = id
		}
		seenTop := map[uint32]bool{}
		for _, c := range res.Menu {
			key := strings.ToLower(c.ID)
			if _, dup := n.menu[key]; dup {
				continue
			}
			e := menuEntry{name: c.Name, path: c.Path}
			if cat, ok := catOf[c.Menu]; ok {
				e.category = cat
				if !seenTop[c.Menu] {
					seenTop[c.Menu] = true
					n.cats = append(n.cats, Category{ID: cat, Name: topName(res.Tops, c.Menu)})
					usedCats[cat] = true
				}
			}
			n.menu[key] = e
		}
		n.menuCount = len(n.menu)
	}
	// Table categories after the menus', for the ones some table command uses
	// and no menu category already has the id.
	for _, c := range t.Categories {
		if usedCats[c.ID] {
			continue
		}
		for _, tc := range n.table {
			if tc.category == c.ID {
				n.cats = append(n.cats, Category{ID: c.ID, Name: tableCatName[c.ID]})
				usedCats[c.ID] = true
				break
			}
		}
	}
	return n, menuErr
}

func topName(tops []MenuTop, id uint32) string {
	for _, t := range tops {
		if t.ID == id {
			return t.Name
		}
	}
	return ""
}

// readMenuResource reads and parses the main resource of a CSP language,
// falling back to English when the folder of that language has none.
func readMenuResource(fsys fs.FS, csplang string) (*Resource, error) {
	var firstErr error
	for _, l := range []string{csplang, "english"} {
		data, err := readLimited(fsys, path.Join("resource", l, MainResourceName), maxResourceSize)
		if err != nil {
			if firstErr == nil {
				firstErr = fmt.Errorf("cspnames: main resource (%s): %w", l, err)
			}
			if l == "english" {
				break
			}
			continue
		}
		res, err := ParseResource(data)
		if err != nil {
			return nil, fmt.Errorf("cspnames: main resource (%s): %w", l, err)
		}
		return res, nil
	}
	return nil, firstErr
}

// Command returns the name of a command. menucommandtype and menucommand are
// the two columns of the shortcut file ("advancedcommand" or "basiccommand",
// and the command id). path is the menu path (menu commands) or the group
// path (the others) without the name itself; category is the ID of a
// Category. ok is false when no source has a name; the caller shows the id.
func (n *Names) Command(menucommandtype, menucommand string) (name string, path []string, category string, ok bool) {
	_ = menucommandtype // ids are unique across both types
	key := strings.ToLower(menucommand)
	if e, found := n.menu[key]; found {
		return e.name, append([]string(nil), e.path...), e.category, true
	}
	if e, found := n.table[key]; found {
		return e.name, append([]string(nil), e.path...), e.category, true
	}
	if p, found := n.plug.lookup(menucommand); found {
		var pp []string
		category = ""
		if c, ok := n.category("filter"); ok {
			pp = append(pp, c.Name)
			category = c.ID
		}
		if p.category != "" {
			pp = append(pp, p.category)
		}
		return p.name, pp, category, true
	}
	return "", nil, "", false
}

func (n *Names) category(id string) (Category, bool) {
	for _, c := range n.cats {
		if c.ID == id {
			return c, true
		}
	}
	return Category{}, false
}

// Categories lists the categories in display order: the top-level menus in
// the order of the resource, then the groups outside the menus.
func (n *Names) Categories() []Category {
	return append([]Category(nil), n.cats...)
}

// MenuCommands returns how many commands the menu resource named; zero means
// the resource was not read.
func (n *Names) MenuCommands() int { return n.menuCount }
