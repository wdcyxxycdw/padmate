// Package cspnames finds the names CLIP STUDIO PAINT (CSP) shows for its
// commands (ADR-0019). The shortcut file holds only command ids such as
// "filenew"; the text lives elsewhere:
//
//   - Menu commands: the main resource under resource\<language>\ of the
//     install folder has the menus, with the label of every item and the menu
//     path. It is read at run time, so it follows the user's CSP version.
//   - Other commands (canvas scrolling, tool property plus and minus, next
//     sub tool and so on): CSP hard-codes the text in its executable. The
//     package ships a table extracted from CSP 5.1.5 (table.json,
//     regenerated by `padmate-probe csp-names`). The same table holds the
//     tree of CSP's shortcut dialog (groups, their names and the order of
//     the commands), which Layout returns.
//   - Filter plug-ins, whose ids are GUIDs: the name is a string resource in
//     the plug-in DLL, read at run time.
//
// Command looks them up in that order; a command found in none has no name
// and the caller shows the id. The package has no platform dependencies.
// The container format is undocumented; the parser is defensive and reports
// anything unexpected as ErrUnknownFormat.
package cspnames

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"strings"
)

// Node is a node of the shortcut dialog's tree (Names.Layout). A node with
// children is a group, named by Name. ID is the group's id or the command's
// id, lower-case; a group's id is also a command id when the group is itself
// a command ("editquickshape"), which only the user's shortcut file can say.
type Node struct {
	ID       string
	Name     string
	Children []Node
}

type menuEntry struct {
	name string
	path []string
}

type tableEntry struct {
	name string
}

// Names resolves command ids to names. It is safe for concurrent use.
type Names struct {
	zh    bool
	menu  map[string]menuEntry
	table map[string]tableEntry
	plug  *plugins
	tree  []Node
	// MenuCount is the number of commands the menu resource named.
	menuCount int
}

// FilterGroup is the id of the dialog group that filter plug-ins are listed
// under (Names.Command returns it as the group of a plug-in).
const FilterGroup = "filterparent"

// Language returns the CSP resource folder for a padmate UI language:
// "zh-CN" gives "chinese_sc"; everything else gives "english".
func Language(lang string) string {
	if isChinese(lang) {
		return "chinese_sc"
	}
	return "english"
}

func isChinese(lang string) bool {
	l := strings.ToLower(strings.ReplaceAll(lang, "_", "-"))
	return l == "zh" || strings.HasPrefix(l, "zh-") || l == "chinese_sc"
}

// Load reads the names of the CSP installed in installDir, the folder that
// holds CLIPStudioPaint.exe and resource\. lang is padmate's UI language
// ("zh-CN" or "en"). An empty installDir reads nothing: the Names then have
// the bundled table and its tree only (LoadBundled).
//
// A resource that cannot be read or parsed is not fatal: Load then returns
// Names that use the bundled table and the plug-ins only, together with the
// error (for logging; it wraps ErrUnknownFormat when the structure was not
// understood). The returned *Names is never nil.
func Load(installDir, lang string) (*Names, error) {
	if installDir == "" {
		return LoadBundled(lang)
	}
	return loadFS(os.DirFS(installDir), lang)
}

// LoadBundled is Names from the bundled table alone: the dialog tree and the
// names of the commands outside the menus. The menu commands and the filter
// plug-ins have no names.
func LoadBundled(lang string) (*Names, error) {
	return loadFS(emptyFS{}, lang)
}

// emptyFS has no file.
type emptyFS struct{}

func (emptyFS) Open(name string) (fs.File, error) {
	return nil, &fs.PathError{Op: "open", Path: name, Err: fs.ErrNotExist}
}

func loadFS(fsys fs.FS, lang string) (*Names, error) {
	zh := isChinese(lang)
	n := &Names{
		zh:    zh,
		menu:  map[string]menuEntry{},
		table: map[string]tableEntry{},
		plug:  newPlugins(fsys, zh),
	}
	t, err := BundledTable()
	if err != nil {
		return n, err
	}
	for id, c := range t.Commands {
		n.table[id] = tableEntry{name: c.pick(zh)}
	}
	n.tree = layoutOf(t.Tree, zh)
	if _, isEmpty := fsys.(emptyFS); isEmpty {
		return n, nil
	}
	res, menuErr := readMenuResource(fsys, Language(lang))
	if res != nil {
		for _, c := range res.Menu {
			key := strings.ToLower(c.ID)
			if _, dup := n.menu[key]; dup {
				continue
			}
			n.menu[key] = menuEntry{name: c.Name, path: c.Path}
		}
		n.menuCount = len(n.menu)
	}
	return n, menuErr
}

// layoutOf converts table nodes into the nodes of one language.
func layoutOf(nodes []TableNode, zh bool) []Node {
	out := make([]Node, 0, len(nodes))
	for _, t := range nodes {
		n := Node{ID: t.ID}
		if t.IsGroup() {
			n.Name = t.EN
			if zh {
				n.Name = t.ZH
			}
			n.Children = layoutOf(t.Children, zh)
		}
		out = append(out, n)
	}
	return out
}

// readMenuResource reads and parses the main resource of a CSP language,
// falling back to English when the folder of that language has none.
func readMenuResource(fsys fs.FS, csplang string) (*Resource, error) {
	var firstErr error
	for _, l := range []string{csplang, "english"} {
		data, err := readLimited(fsys, path.Join("resource", l, MainResourceName), maxResourceSize)
		if err != nil {
			if firstErr == nil {
				firstErr = fmt.Errorf("cspnames: main resource (%s): %w", l, err)
			}
			if l == "english" {
				break
			}
			continue
		}
		res, err := ParseResource(data)
		if err != nil {
			return nil, fmt.Errorf("cspnames: main resource (%s): %w", l, err)
		}
		return res, nil
	}
	return nil, firstErr
}

// Command returns the name of a command. menucommandtype and menucommand are
// the two columns of the shortcut file ("advancedcommand" or "basiccommand",
// and the command id). path is the menu path (menu commands) or the plug-in's
// group (filters) without the name itself. group is the id of the dialog group
// a command that the dialog tree does not list belongs under: FilterGroup for
// a plug-in, empty for the others. ok is false when no source has a name; the
// caller shows the id.
func (n *Names) Command(menucommandtype, menucommand string) (name string, path []string, group string, ok bool) {
	_ = menucommandtype // ids are unique across both types
	key := strings.ToLower(menucommand)
	if e, found := n.menu[key]; found {
		return e.name, append([]string(nil), e.path...), "", true
	}
	if e, found := n.table[key]; found {
		return e.name, nil, "", true
	}
	if p, found := n.plug.lookup(menucommand); found {
		var pp []string
		if g, ok := n.Group(FilterGroup); ok {
			pp = append(pp, g)
			group = FilterGroup
		}
		if p.category != "" {
			pp = append(pp, p.category)
		}
		return p.name, pp, group, true
	}
	return "", nil, "", false
}

// Group returns the localized name of a group of the dialog (the first one
// with the id, in dialog order).
func (n *Names) Group(id string) (string, bool) {
	var find func(nodes []Node) (string, bool)
	find = func(nodes []Node) (string, bool) {
		for _, g := range nodes {
			if len(g.Children) == 0 {
				continue
			}
			if g.ID == id {
				return g.Name, true
			}
			if name, ok := find(g.Children); ok {
				return name, true
			}
		}
		return "", false
	}
	return find(n.tree)
}

// Layout returns the shortcut dialog's tree in dialog order: top-level
// groups with their children. The result is shared; callers must not modify
// it.
func (n *Names) Layout() []Node { return n.tree }

// MenuCommands returns how many commands the menu resource named; zero means
// the resource was not read.
func (n *Names) MenuCommands() int { return n.menuCount }
